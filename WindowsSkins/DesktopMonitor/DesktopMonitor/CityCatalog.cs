	public static CityInfo Resolve(string name)
	{
		foreach (CityInfo item in PlaceCatalog.Search(name, 8))
		{
			if (string.Equals(PlaceCatalog.Normalize(item.Name), PlaceCatalog.Normalize(name), StringComparison.Ordinal))
			{
				return item;
			}
		}
		foreach (CityInfo entry in Entries)
		{
			if (string.Equals(entry.Name, name, StringComparison.Ordinal))
			{
				return entry;
			}
		}
		return null;
	}

